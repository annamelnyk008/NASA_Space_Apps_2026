export function interpTab(tab, x) {
  if (x <= tab[0][0]) return tab[0][1];
  for (var i = 1; i < tab.length; i++) {
    if (x <= tab[i][0]) { var a = tab[i - 1], b = tab[i]; return a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]); }
  }
  return tab[tab.length - 1][1];
}
